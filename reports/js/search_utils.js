// 일치 여부 판정용: 공백을 전부 제거합니다.
function searchStripWhitespace(str) {
    return (str || '').replace(/\s+/g, '');
}

// 스니펫 등 화면 표시용: 줄바꿈/중복 공백만 한 칸으로 합쳐 가독성을 유지합니다.
function searchCollapseWhitespace(str) {
    return (str || '').replace(/\s+/g, ' ').trim();
}
